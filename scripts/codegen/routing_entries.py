#!/usr/bin/env python3
# -*- coding: UTF-8 -*-

"""
从两个域的声明生成 TypeScript 导航入口

产物两份（都用不上对方的段，拆开免得互相拖累）：
    app.entries.generated.ts   入口表 + 每个入口的载荷类型 + 地址链父表
    help.entries.generated.ts  帮助文档的深链句柄

用法：
    uv run ./scripts/codegen/routing_entries.py
"""

import json
import re
import sys
from pathlib import Path

from common.constant.paths import (
    FRONTEND_APP_ENTRIES_PATH,
    FRONTEND_DIR,
    FRONTEND_HELP_ENTRIES_PATH,
    PROJECT_BASE_DIR,
    RESOURCES_DIR,
)
from common.logger import error, success
from util.sigint import graceful_sigint

APP_META_PATH = FRONTEND_DIR / "src" / "lib" / "resources" / "app" / "meta.json"
HELP_META_PATH = FRONTEND_DIR / "src" / "lib" / "resources" / "help" / "meta.json"
HELP_DOC_ROOT = RESOURCES_DIR / "help"

#: 两个域的 host
APP_HOST = "app"
HELP_HOST = "help"

#: 应用内地址前缀，与 `frontend/src/lib/routing/address.ts` 的 `ROUTE_PREFIX` 一致
ROUTE_PREFIX = "#/"

#: 载荷类型语法里直接认作 TS 原语的标识符；其余标识符一律当成 `$types` 里的类型名
PAYLOAD_PRIMITIVES = frozenset({"string", "number", "boolean"})

#: 声明里的 `payload` 字段名
PAYLOAD_KEY = "payload"

_HEADER = (
    "// This file is generated by scripts/codegen/routing_entries.py, "
    "please do not manually modify it.\n"
)
_IDENT_RE = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")
#: 标题锚点声明 `## 标题 {#kebab-name}`
_ANCHOR_RE = re.compile(r"\{#([A-Za-z0-9_-]+)}")
#: 锚点语法：小写字母数字，单连字符分隔（与 `helpAddress.ts` 的 `KEBAB_RE` 一致）
_KEBAB_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")


def handle_of(name: str) -> str:
    """名字 → 代码句柄：`edit-student` → `editStudent`，`RELEASE_NOTES.md` → `releaseNotes`

    先去掉扩展名，再按 `-`/`_` 断词；**逐段小写归一**后首段保持小写、其余段首字母大写
    （`RELEASE_NOTES` 必须给出 `releaseNotes` 而不是 `releaseNOTES`）。
    """
    stem = re.sub(r"\.[A-Za-z0-9]+$", "", name)
    head, *rest = re.split(r"[-_]+", stem)
    return head.lower() + "".join(part[:1].upper() + part[1:].lower() for part in rest)


def join_handle(prefix: str, suffix: str) -> str:
    """两级句柄拼一级：`quick-start` + `install-app` → `quickStartInstallApp`"""
    return prefix + suffix[:1].upper() + suffix[1:]


class MetaError(Exception):
    """声明本身不合法"""


def read_nodes(meta_path: Path) -> dict[str, tuple[str | None, object]]:
    """读取并校验一张节点表，返回 `{节点名: (parentId, payload 声明)}`（保留书写顺序）

    `payload` 键缺省时返回 `None`；它的语法见 `payload_type`。
    """
    if not meta_path.exists():
        raise MetaError(f"节点表不存在: {meta_path}")

    try:
        raw = json.loads(meta_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as e:
        raise MetaError(f"节点表不是合法 JSON: {e}") from e

    nodes = raw.get("nodes")
    if not isinstance(nodes, dict) or not nodes:
        raise MetaError(f"{meta_path.name} 缺少非空的 `nodes` 对象")

    out: dict[str, tuple[str | None, object]] = {}
    for name, node in nodes.items():
        if not isinstance(node, dict):
            raise MetaError(f"节点 `{name}` 必须是对象")
        if "parentId" not in node:
            raise MetaError(f"节点 `{name}` 缺少 `parentId`（根节点写 null）")
        parent = node["parentId"]
        if parent is not None and not isinstance(parent, str):
            raise MetaError(f"节点 `{name}` 的 `parentId` 必须是字符串或 null")
        out[name] = (parent, node.get(PAYLOAD_KEY))

    for name, (parent, _) in out.items():
        if parent is not None and parent not in out:
            raise MetaError(f"节点 `{name}` 的 parentId `{parent}` 不在表中")
        if parent == name:
            raise MetaError(f"节点 `{name}` 的 parentId 指向自己")

    # 顺着 parentId 往上走，走不到根即为环
    for name in out:
        seen = set()
        cur: str | None = name
        while cur is not None:
            if cur in seen:
                raise MetaError(f"`parentId` 链成环，涉及节点 `{cur}`")
            seen.add(cur)
            cur = out[cur][0]

    return out


def check_handles(pairs: list[tuple[str, str, str]]) -> None:
    """句柄必须合法且互不相同（否则生成出来的 TS 会静默互相覆盖）

    :param pairs: `(域标签, 句柄, 来源说明)` 列表
    """
    owner: dict[str, str] = {}
    for label, handle, source in pairs:
        if not _IDENT_RE.match(handle):
            raise MetaError(f"[{label}] {source} 推不出合法的代码句柄（得到 `{handle}`）")
        if handle in owner:
            raise MetaError(
                f"[{label}] {source} 与 {owner[handle]} 推出同一个句柄 `{handle}`，"
                "请改名使其在去掉连字符后仍可区分"
            )
        owner[handle] = source


def payload_type(spec: object, where: str, refs: set[str]) -> str:
    """载荷声明 → TS 类型文本

    三条规则，覆盖得住"id 或 id 集合"到"预填对象"：

    - 字符串：`string` / `number` / `boolean` 是原语；**其余标识符当成 `$types` 里的类型名**
      （如 `ImportFile`），并记进 `refs` 以便生成 `import type`
    - 单元素数组：`T[]`（多元素没有定义，直接报错，免得被误读成元组）
    - 对象：`{ 字段: 类型 }`，值递归按本函数解释

    白名单之外的**类型本身**无法表达（没有 `bigint`、没有 `Set`），于是"载荷必须可 JSON
    序列化"这条约束在声明期成立，运行期不必再校验一次。

    :param where: 出错信息里的位置说明
    :param refs: 收集需要从 `$types` 导入的类型名（会被就地修改）
    """
    if isinstance(spec, str):
        if spec in PAYLOAD_PRIMITIVES:
            return spec
        if not _IDENT_RE.match(spec):
            raise MetaError(f"{where} 的 payload 类型 `{spec}` 不是合法标识符")
        refs.add(spec)
        return spec
    if isinstance(spec, list):
        if len(spec) != 1:
            raise MetaError(
                f"{where} 的 payload 数组必须恰好一个元素（`[\"number\"]` 表示 `number[]`）"
            )
        return f"{payload_type(spec[0], where, refs)}[]"
    if isinstance(spec, dict):
        if not spec:
            raise MetaError(f"{where} 的 payload 对象不能为空")
        fields: list[str] = []
        for field, value in spec.items():
            if not _IDENT_RE.match(field):
                raise MetaError(f"{where} 的 payload 字段 `{field}` 不是合法标识符")
            fields.append(f"{field}: {payload_type(value, where, refs)}")
        return "{ " + "; ".join(fields) + " }"
    raise MetaError(f"{where} 的 payload 只能是字符串、单元素数组或对象")


def render_app(nodes: dict[str, tuple[str | None, object]]) -> str:
    """渲染 app 段：host + 载荷类型表 + 句柄表 + 父表"""
    names: list[str] = list(nodes)
    refs: set[str] = set()

    payloads = "\n".join(
        f'  "{name}": {payload_type(payload, f"节点 `{name}`", refs) if payload is not None else "undefined"}'
        for name, (_, payload) in nodes.items()
    )
    handles = ",\n".join(f'  {handle_of(name)}: "{name}"' for name in names)
    parents = ",\n".join(
        f'  "{name}": {json.dumps(parent)}' for name, (parent, _) in nodes.items()
    )

    imports = ""
    if refs:
        imports = f'import type {{{", ".join(sorted(refs))}}} from "$types";\n\n'

    return (
        _HEADER
        + "// source: frontend/src/lib/resources/app/meta.json\n"
        + "\n"
        + imports
        + "/** host */\n"
        + f'export const APP_HOST = "{APP_HOST}";\n'
        + "\n"
        + "/**\n"
        + " * 每个入口吃的载荷：`undefined` 表示该入口不吃载荷。\n"
        + " *\n"
        + " * 由 `app/meta.json` 节点的 `payload` 键派生；只允许能 JSON 序列化的形状\n"
        + " * （跨窗口投递要过 `serde_json::Value`），所以 `bigint` / `Set` 写不出来。\n"
        + " */\n"
        + "export interface AppEntryPayload {\n"
        + f"{payloads}\n"
        + "}\n"
        + "\n"
        + "/** 入口名 */\n"
        + "export type AppEntryId = keyof AppEntryPayload;\n"
        + "\n"
        + "/**\n"
        + " * 入口句柄\n"
        + " */\n"
        + "export const AppEntry = {\n"
        + f"{handles}\n"
        + "} as const satisfies Record<string, AppEntryId>;\n"
        + "\n"
        + "/** 入口 → 父入口；null 表示卡片 */\n"
        + "export const APP_ENTRY_PARENT = {\n"
        + f"{parents}\n"
        + "} as const satisfies Record<AppEntryId, AppEntryId | null>;\n"
    )


def render_help(
    nodes: dict[str, tuple[str | None, object]], anchors: dict[str, list[str]]
) -> str:
    """渲染 help 段：句柄 → 完整地址"""
    lines: list[str] = []
    skipped: list[str] = []

    for doc in nodes:
        if doc not in anchors:
            skipped.append(doc)
            continue
        lines.append(f'  {handle_of(doc)}: "{ROUTE_PREFIX}{HELP_HOST}/{doc}"')
        for anchor in anchors[doc]:
            handle = join_handle(handle_of(doc), handle_of(anchor))
            lines.append(f'  {handle}: "{ROUTE_PREFIX}{HELP_HOST}/{doc}/{anchor}"')

    if not lines:
        raise MetaError("没有一篇文档能找到 md 源，HelpEntry 会生成空表")

    note = ""
    if skipped:
        note = (
            "// 未生成句柄的节点（既无 resources/help/<id>/ 目录、也无仓库根同名文件）："
            + ", ".join(skipped)
            + "\n"
        )

    return (
        _HEADER
        + "// source: frontend/src/lib/resources/help/meta.json + *.md\n"
        + "\n"
        + "/**\n"
        + " * 帮助窗口的深链句柄：句柄 → 地址（`#/help/<文档>[/<锚点>]`）\n"
        + " *\n"
        + " * 由 `help/meta.json` 的文档树与各文档 md 里的 `{#锚点}` 派生，\n"
        + " * 文档级句柄为文档名、锚点级句柄为文档名 + 锚点名。\n"
        + " * md 源 = `resources/help/<id>/` 目录，或仓库根同名文件（README.md / LICENSE / …）。\n"
        + " */\n"
        + f"{note}"
        + "export const HelpEntry = {\n"
        + ",\n".join(lines)
        + "\n} as const satisfies Record<string, `#/help/${string}`>;\n"
    )


def doc_sources(doc: str) -> list[Path]:
    """一篇文档的 md 源。两处各查一次：`resources/help/<id>/` 目录，或仓库根同名文件

    （`README.md`/`LICENSE`/`CHANGELOG.md`/`RELEASE_NOTES.md` 的正文不在 resources 下，
    文件却在仓库根，锚点也照常声明 —— 故一并当作文档源。）
    """
    doc_dir = HELP_DOC_ROOT / doc
    if doc_dir.is_dir():
        return sorted(doc_dir.glob("*.md"))

    root_file = PROJECT_BASE_DIR / doc
    return [root_file] if root_file.is_file() else []


def scan_anchors(mds: list[Path]) -> list[str]:
    """扫描一篇文档所有 md 源里的锚点声明，按首次出现的顺序取并集"""
    anchors: list[str] = []
    for md in mds:
        rel = md.relative_to(PROJECT_BASE_DIR).as_posix()
        for anchor in _ANCHOR_RE.findall(md.read_text(encoding="utf-8")):
            if not _KEBAB_RE.match(anchor):
                raise MetaError(f"{rel} 里的锚点 `{anchor}` 不是 kebab-case，无法进地址")
            if anchor not in anchors:
                anchors.append(anchor)
    return anchors


def write(path: Path, content: str) -> None:
    """按仓库约定写文件：UTF-8、行尾 LF"""
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as f:
        f.write(content)


def generate() -> None:
    """
    读取两张节点表与各文档锚点，渲染并写入两份生成物

    :raise MetaError: 声明本身不合法（节点表结构、句柄重名、载荷语法、锚点格式等）
    """
    app_nodes = read_nodes(APP_META_PATH)
    # 句柄唯一性必须在生成前查：同一域内重名会静默覆盖成一条
    check_handles([("app", handle_of(name), f"节点 `{name}`") for name in app_nodes])

    help_nodes = read_nodes(HELP_META_PATH)
    help_anchors: dict[str, list[str]] = {}
    help_pairs: list[tuple[str, str, str]] = []
    for doc in help_nodes:
        mds = doc_sources(doc)
        if not mds:
            continue
        anchors = scan_anchors(mds)
        help_anchors[doc] = anchors
        help_pairs.append(("help", handle_of(doc), f"文档 `{doc}`"))
        for anchor in anchors:
            help_pairs.append(
                (
                    "help",
                    join_handle(handle_of(doc), handle_of(anchor)),
                    f"`{doc}` 的锚点 `{anchor}`",
                )
            )
    check_handles(help_pairs)

    write(FRONTEND_APP_ENTRIES_PATH, render_app(app_nodes))
    write(FRONTEND_HELP_ENTRIES_PATH, render_help(help_nodes, help_anchors))

    app_roots = sum(1 for parent, _ in app_nodes.values() if parent is None)
    payload_count = sum(1 for _, payload in app_nodes.values() if payload is not None)
    anchor_count = sum(len(anchors) for anchors in help_anchors.values())
    success(
        f"已生成 {FRONTEND_APP_ENTRIES_PATH.name}（{len(app_nodes)} 个入口 / {app_roots} 个根 / "
        f"{payload_count} 个带载荷）与 {FRONTEND_HELP_ENTRIES_PATH.name}"
        f"（{len(help_anchors)} 篇文档 / {anchor_count} 个锚点）"
    )


def main() -> int:
    try:
        generate()
    except MetaError as e:
        error(f"生成失败: {e}")
        return 1
    return 0


if __name__ == "__main__":
    with graceful_sigint():
        sys.exit(main())
