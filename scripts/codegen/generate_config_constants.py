from pathlib import Path
from typing import List, Tuple, Optional

import util
from common.constant.paths import RESOURCES_DIR, BACKEND_DIR, FRONTEND_DIR
from common.logger import warning, error, success

CONFIG_KEY_FILE = RESOURCES_DIR / "develop" / "config.key"
RS_OUTPUT_FILE = BACKEND_DIR / "src" / "common" / "constant" / "app_config_keys.rs"
TS_OUTPUT_FILE = FRONTEND_DIR / "src" / "lib" / "constants" / "AppConfigKeys.ts"


def read_config_file(config_path: Path) -> Optional[str]:
    if not config_path.exists():
        warning(f"配置文件不存在: {config_path}")
        warning(f"当前工作目录是: {Path.cwd()}")
        return None

    try:
        return config_path.read_text(encoding='utf-8')
    except Exception as e:
        warning(f"读取配置文件失败: {config_path}")
        warning(f"错误详情: {e}")
        return None


def parse_config_lines(content: str) -> Tuple[List[str], List[str]]:
    """
    解析配置行，生成 Rust 和 TypeScript 常量定义

    Args:
        content: 配置文件内容

    Returns:
        (rust_lines, ts_lines) 元组
    """
    lines = content.splitlines()

    rs_lines = []
    ts_lines = []

    for line in lines:
        line = line.strip()

        # 跳过空行和注释行
        if not line or line.startswith('#') or line.startswith('//'):
            continue

        # 生成常量名：大写，替换 . 和 - 为 _
        const_name = line.upper().replace('.', '_').replace('-', '_')

        # Rust 常量
        rs_lines.append(f'    pub const {const_name}: &str = "{line}";')

        # TypeScript 常量
        ts_lines.append(f'  {const_name}: "{line}" as const,')

    return rs_lines, ts_lines


def generate_rs_content(rs_lines: List[str]) -> str:
    """
    生成 Rust 文件内容

    Args:
        rs_lines: Rust 常量定义行列表

    Returns:
        Rust 文件完整内容
    """
    return f"""// Automatically generated by build.rs, please do not manually modify.

{chr(10).join(rs_lines)}

"""


def generate_ts_content(ts_lines: List[str]) -> str:
    """
    生成 TypeScript 文件内容

    Args:
        ts_lines: TypeScript 常量定义行列表

    Returns:
        TypeScript 文件完整内容
    """
    return f"""// Automatically generated by build.rs, please do not manually modify.

export const APP_CONFIG_KEYS = {{
{chr(10).join(ts_lines)}
}} as const;

export type AppConfigKeys = keyof typeof APP_CONFIG_KEYS;
"""


def write_rs_file(output_path: Path, content: str) -> None:
    """
    写入 Rust 文件

    Args:
        output_path: 输出文件路径
        content: 文件内容

    Raises:
        RuntimeError: 写入失败时抛出
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    try:
        output_path.write_text(content, encoding='utf-8')
    except Exception as e:
        util.fail(f"写入 Rust 文件失败: {output_path} - {e}")


def write_ts_file(output_path: Path, content: str) -> None:
    """
    写入 TypeScript 文件

    Args:
        output_path: 输出文件路径
        content: 文件内容

    Raises:
        RuntimeError: 写入失败时抛出
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    try:
        output_path.write_text(content, encoding='utf-8')
    except Exception as e:
        util.fail(f"写入 TypeScript 文件失败: {output_path} - {e}")


def generate_config_constant(config_path: Path, rs_output_path: Path, ts_output_path: Path) -> int:
    """从配置文件生成 Rust 和 TypeScript 常量定义"""

    content = read_config_file(config_path)
    if content is None:
        warning(f"文件 {config_path} 为空，没有待生成的内容")
        return 1

    rs_lines, ts_lines = parse_config_lines(content)

    rs_content = generate_rs_content(rs_lines)
    ts_content = generate_ts_content(ts_lines)

    try:
        write_rs_file(rs_output_path, rs_content)
        write_ts_file(ts_output_path, ts_content)
    except RuntimeError as e:
        error(str(e))
        return False

    if not rs_lines:
        warning("配置文件中没有有效的配置项，已清空所有常量")
        return True

    success(f"配置文件 {rs_output_path} 生成成功，大小为 {rs_output_path.stat().st_size / 1024:.3f} KB")
    success(f"配置文件 {ts_output_path} 生成成功，大小为 {ts_output_path.stat().st_size / 1024:.3f} KB")
    return True


if __name__ == "__main__":
    SystemExit(generate_config_constant(CONFIG_KEY_FILE, RS_OUTPUT_FILE, TS_OUTPUT_FILE))
